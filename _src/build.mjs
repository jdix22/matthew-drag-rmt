// node _src/build.mjs  -> writes every page, data.js, robots.txt, sitemap.xml, 404.html
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITE, NOINDEX, F, PRICES, head, header, footer, icon } from './site.mjs';
import { home } from './pages/home.mjs';
import { fst, mobile, recovery } from './pages/services.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (p, s) => { const f = join(ROOT, p); mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, s); console.log('wrote', p); };

const pages = [home, fst, mobile, recovery];
for (const p of pages) out((p.path || '') + 'index.html', head(p) + '\n<body>\n' + header(p) + p.body() + '\n' + footer(p));

// 404 (root-relative base works on the real domain; on github.io it lives at the repo root too)
const nf = { path: '404.html', base: SITE.replace(/^https?:\/\/[^/]+/, ''), title: 'Page not found | Matthew Drag RMT', description: 'This page has moved. Book sports massage in Newmarket with Matthew Drag, RMT.', ld: [] };
out('404.html', (NOINDEX ? head(nf) : head(nf).replace('<link rel="canonical"', '<meta name="robots" content="noindex">\n<link rel="canonical"')) + '\n<body>\n' + header(nf) + `
<main id="main"><section class="hero hero-sub" data-mile="0"><div class="wrap hero-copy" style="padding-block:120px">
<p class="neon"><span class="neon-a">Wrong turn</span> <span class="neon-b">at mile 3</span></p>
<h1>That page isn't on the route.</h1>
<p class="lede">It may have moved when the site was rebuilt.</p>
<div class="hero-cta"><a class="btn btn-neon" href="${nf.base}">Back to the start ${icon.arrow}</a><a class="btn btn-ghost-light" href="${F.janeStaff}">Book online</a></div>
</div></section></main>\n` + footer(nf));

// data for site.js
out('assets/js/data.js', `/* generated by _src/build.mjs from _src/site.mjs — edit there */\nwindow.MD=${JSON.stringify({ jane: F.jane, staff: F.janeStaff, email: F.email, tel: F.tel, phone: F.phone, hours: F.hours, prices: PRICES })};\n`);

out('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${SITE}sitemap.xml\n`);
const today = new Date().toISOString().slice(0, 10);
out('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pages.map(p => `  <url><loc>${SITE}${p.path}</loc><lastmod>${today}</lastmod></url>`).join('\n')}\n</urlset>\n`);
if (NOINDEX) console.log('NOTE: noindex is ON (demo). Turn off in _src/site.mjs at launch.');
